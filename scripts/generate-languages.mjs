#!/usr/bin/env node

/**
 * generate-languages.mjs - Generates the static language catalog and alias mapping
 * from bundled Highlight.js.
 *
 * Source of truth: compose-highlight/src/main/assets/compose-highlight/highlight.min.js
 * Output: compose-highlight/src/main/kotlin/dev/hossain/highlight/engine/internal/GeneratedLanguages.kt
 *
 * Usage:
 *   node scripts/generate-languages.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, '..');
const BUNDLE_PATH = path.join(
  REPO_ROOT,
  'compose-highlight/src/main/assets/compose-highlight/highlight.min.js'
);
const OUTPUT_FILE = path.join(
  REPO_ROOT,
  'compose-highlight/src/main/kotlin/dev/hossain/highlight/engine/internal/GeneratedLanguages.kt'
);

if (!fs.existsSync(BUNDLE_PATH)) {
  console.error(`Error: Bundle file not found at ${BUNDLE_PATH}`);
  process.exit(1);
}

const bundledCode = fs.readFileSync(BUNDLE_PATH, 'utf8');
const sandbox = {};
vm.runInNewContext(bundledCode, sandbox);

if (!sandbox.hljs || typeof sandbox.hljs.listLanguages !== 'function') {
  console.error('Error: hljs.listLanguages is not available in sandbox');
  process.exit(1);
}

const rawLanguages = sandbox.hljs.listLanguages();
console.log(`Found ${rawLanguages.length} raw languages in bundled Highlight.js`);

// Highlight.js aliases html under xml, but in Compose Highlight and downstream apps,
// html is a first-class language identifier. Include html in allLanguages.
const languageSet = new Set(rawLanguages);
languageSet.add('html');
const sortedLanguages = Array.from(languageSet).sort((a, b) => a.localeCompare(b));

console.log(`Total canonical languages (including html): ${sortedLanguages.length}`);

// Extract aliases from each language definition
const aliasMap = new Map();

for (const lang of rawLanguages) {
  const def = sandbox.hljs.getLanguage(lang);
  if (def && Array.isArray(def.aliases)) {
    for (const alias of def.aliases) {
      const lowerAlias = alias.toLowerCase();
      // If alias collision occurs, keep the one that matches hljs.getLanguage resolution
      if (aliasMap.has(lowerAlias)) {
        const resolved = sandbox.hljs.getLanguage(lowerAlias);
        if (resolved && resolved.name === def.name) {
          aliasMap.set(lowerAlias, lang);
        }
      } else {
        aliasMap.set(lowerAlias, lang);
      }
    }
  }
}

// Special cases: html & htm
aliasMap.set('html', 'html');
aliasMap.set('htm', 'html');

// Sort aliases alphabetically for deterministic code generation
const sortedAliases = Array.from(aliasMap.entries()).sort(([a], [b]) => a.localeCompare(b));
console.log(`Extracted ${sortedAliases.length} unique aliases`);

// Format Kotlin file
const languagesListEntries = sortedLanguages.map((lang) => `            "${lang}",`).join('\n');
const aliasesMapEntries = sortedAliases
  .map(([alias, target]) => `            "${alias}" to "${target}",`)
  .join('\n');

const kotlinContent = `package dev.hossain.highlight.engine.internal

/**
 * Automatically generated by \`scripts/generate-languages.mjs\` from bundled Highlight.js (${sandbox.hljs.versionString}).
 * Do not edit this file directly.
 *
 * Total languages: ${sortedLanguages.length}
 * Total aliases: ${sortedAliases.length}
 */
internal object GeneratedLanguages {
    /**
     * All supported language identifiers in alphabetical order.
     */
    val ALL: List<String> =
        listOf(
${languagesListEntries}
        )

    /**
     * Official Highlight.js aliases mapped to their canonical language identifiers.
     */
    val ALIASES: Map<String, String> =
        mapOf(
${aliasesMapEntries}
        )
}
`;

fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
fs.writeFileSync(OUTPUT_FILE, kotlinContent, 'utf8');

console.log(`Successfully generated ${path.relative(REPO_ROOT, OUTPUT_FILE)}`);
